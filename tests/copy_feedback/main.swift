import Foundation

var feedback = CopyFeedback()
assert(feedback.id == nil && !feedback.expire(now: 0))
feedback.show("live/a", now: 10)
assert(feedback.id == "live/a")
assert(!feedback.expire(now: 11.499999))
assert(feedback.expire(now: 11.5) && feedback.id == nil && feedback.deadline == nil)
feedback.show("live/a", now: 20)
feedback.show("live/a", now: 21)
assert(!feedback.expire(now: 21.5) && feedback.id == "live/a")
assert(feedback.expire(now: 22.5))
feedback.show("live/a", now: 30)
feedback.show("review/b", now: 31)
assert(feedback.id == "review/b" && !feedback.expire(now: 31.5))
feedback.show("review/toolbar", now: 32)
assert(feedback.id == "review/toolbar" && !feedback.expire(now: 32.5))
assert(feedback.expire(now: 33.5) && feedback.id == nil)
assert(!feedback.expire(now: 40))
assert(CopyFeedback.fadeDuration == 0.15)
print("PASS copy feedback: 1.5s boundary, repeat resets, cross-surface single target, 150ms fade")
